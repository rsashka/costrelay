#!/bin/sh
# Install costrelayd as a system service and grant its user permission to
# restart only the units exposed by the panel.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TEMPLATE="$ROOT/deploy/costrelayd.service.in"
UNIT=/etc/systemd/system/costrelayd.service
SUDOERS=/etc/sudoers.d/costrelay-restart
BIN="${COSTRELAY_BIN:-$ROOT/build/costrelayd}"
CONFIG="${COSTRELAY_CONFIG:-$ROOT/config/costrelay.yaml}"
RUN_USER="${SUDO_USER:-$(stat -c '%U' "$ROOT")}"
if [ "$RUN_USER" = "root" ]; then
    RUN_USER="$(stat -c '%U' "$ROOT")"
fi
RUN_GROUP="$(stat -c '%G' "$ROOT")"
RUN_HOME="$(getent passwd "$RUN_USER" | cut -d: -f6)"

if [ "$(id -u)" -ne 0 ]; then
    echo "error: run with sudo $0" >&2
    exit 1
fi
if [ -z "$RUN_HOME" ]; then
    echo "error: no home directory for $RUN_USER" >&2
    exit 1
fi
if [ ! -x "$BIN" ]; then
    echo "error: costrelayd binary not found: $BIN (build it first)" >&2
    exit 1
fi
if [ ! -f "$CONFIG" ]; then
    echo "error: config not found: $CONFIG" >&2
    exit 1
fi

sed -e "s|@ROOT@|$ROOT|g" \
    -e "s|@USER@|$RUN_USER|g" \
    -e "s|@GROUP@|$RUN_GROUP|g" \
    -e "s|@HOME@|$RUN_HOME|g" \
    -e "s|@BIN@|$BIN|g" \
    -e "s|@CONFIG@|$CONFIG|g" \
    "$TEMPLATE" > "$UNIT"
chmod 644 "$UNIT"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
cat > "$TMP" <<EOF
# Generated by costrelayd deploy/install-service.sh.
$RUN_USER ALL=(root) NOPASSWD: /usr/bin/systemctl restart --no-block dsh-web.service
$RUN_USER ALL=(root) NOPASSWD: /usr/bin/systemctl restart --no-block strata.service
$RUN_USER ALL=(root) NOPASSWD: /usr/bin/systemctl restart --no-block costrelayd.service
EOF
if ! command -v visudo >/dev/null 2>&1; then
    echo "error: visudo not found; refusing to install unvalidated sudoers" >&2
    exit 1
fi
visudo -cf "$TMP" >/dev/null
install -m 0440 "$TMP" "$SUDOERS"

systemctl daemon-reload
# The DSH unit embeds this checkout's absolute path. After a move it exists but
# points at the old directory, so reinstall it whenever its ExecStart is stale.
DSH_UNIT=/etc/systemd/system/dsh-web.service
DSH_REINSTALLED=0
if [ -x "$ROOT/dsh/install-service.sh" ] &&
   { [ ! -f "$DSH_UNIT" ] || ! grep -qF "ExecStart=$ROOT/dsh/start-local.sh" "$DSH_UNIT"; }; then
    # install-service.sh stops the unit; remember that it must come back up.
    DSH_WAS_ACTIVE=0
    systemctl is-active --quiet dsh-web.service && DSH_WAS_ACTIVE=1
    "$ROOT/dsh/install-service.sh"
    DSH_REINSTALLED=$DSH_WAS_ACTIVE
fi
systemctl enable dsh-web.service 2>/dev/null || true
if [ "$DSH_REINSTALLED" -eq 1 ]; then
    systemctl start dsh-web.service
    echo "restarted: dsh-web.service"
fi
systemctl enable strata.service 2>/dev/null || true
systemctl enable costrelayd.service

echo "installed: $UNIT"
echo "installed: $SUDOERS"
echo "services enabled at boot: dsh-web.service strata.service costrelayd.service"

if systemctl is-active --quiet costrelayd.service; then
    systemctl restart costrelayd.service
    echo "restarted: costrelayd.service"
elif command -v ss >/dev/null 2>&1 && ss -ltn 'sport = :8443' 2>/dev/null | grep -q LISTEN; then
    echo "warning: port 8443 is already in use (probably a manually started costrelayd)." >&2
    echo "stop the manual process, then run: sudo systemctl start costrelayd.service" >&2
else
    systemctl start costrelayd.service
    echo "started: costrelayd.service"
fi